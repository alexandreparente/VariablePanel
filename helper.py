# ── shared helpers ───────────────────────────────────────────────────────────


def _is_excluded(name):
    """Check a file/dir basename against PACKAGE_EXCLUDES patterns."""
    return any(fnmatch.fnmatch(name, p) for p in PACKAGE_EXCLUDES)


def find_source_files():
    """
    Recursively find all .py files under REPO_ROOT, skipping excluded
    directories/files (test/, help/, build/, .venv/, __pycache__/, helper.py, etc.).

    Used to build the file list passed to pylupdate5.
    """
    source_files = []
    for root, dirs, files in os.walk(REPO_ROOT):
        # Prune excluded directories in-place so os.walk doesn't descend into them
        dirs[:] = [d for d in dirs if not _is_excluded(d)]
        for fname in files:
            if fname.endswith(".py") and not _is_excluded(fname):
                source_files.append(os.path.join(root, fname))
    return sorted(source_files)


# ── translate ────────────────────────────────────────────────────────────────


def translate(locale=None):
    """
    Update translation sources (.ts) and compile them to .qm files.

    :param locale: Locale to process (e.g., 'en', 'pt_BR').
                   Omit to process all locales.

    Examples:
      python helper.py translate
      python helper.py translate pt_BR
    """
    print("Updating translation files...")

    i18n_dir = os.path.join(REPO_ROOT, "i18n")

    if locale:
        ts_files = glob.glob(os.path.join(i18n_dir, f"{PLUGIN_DISPLAY}_{locale}.ts"))
        if not ts_files:
            print(f"Error: No .ts file found for locale '{locale}' in {i18n_dir}")
            return
    else:
        ts_files = glob.glob(os.path.join(i18n_dir, f"{PLUGIN_DISPLAY}_*.ts"))

    if not ts_files:
        print(f"Error: No .ts files found in {i18n_dir}")
        return

    # Plugin Python sources — recursive scan, skipping test/, help/, .venv/, etc.
    source_files = find_source_files()

    try:
        if source_files:
            subprocess.run(
                ["pylupdate5", "-noobsolete"] + source_files + ["-ts"] + ts_files,
                check=True,
            )
        subprocess.run(["lrelease"] + ts_files, check=True)
        print(f"Success: {len(ts_files)} translation file(s) updated.")

    except FileNotFoundError as e:
        print(f"Error: '{e.filename}' not found. Install Qt tools first.")
    except subprocess.CalledProcessError as e:
        print(f"Error during translation process: {e}")


# ── run_tests ────────────────────────────────────────────────────────────────


def run_tests(qgis_version=QGIS_TEST_VERSION, *pytest_args):
    """
    Run the test suite inside a QGIS Docker container.

    :param qgis_version: Docker tag — 'latest', 'release-3_34', or 'all'.
                         'all' runs QGIS_MINIMUM_VERSION and QGIS_MAXIMUM_VERSION.
    :param pytest_args:  Extra arguments forwarded to pytest.

    Examples:
      python helper.py pytest
      python helper.py pytest release-3_34
      python helper.py pytest all
      python helper.py pytest latest -k test_init -vv
    """
    versions = (
        [QGIS_MINIMUM_VERSION, QGIS_MAXIMUM_VERSION]
        if qgis_version == "all"
        else [qgis_version]
    )

    for version in versions:
        image = f"qgis/qgis:{version}"
        print(f"\n Running tests in Docker ({image}) ...")

        result = subprocess.run(
            [
                "docker",
                "run",
                "--rm",
                "-v",
                f"{REPO_ROOT}:/src",
                "--user",
                f"{os.getuid()}:{os.getgid()}",
                "-e",
                "HOME=/tmp",
                image,
                "bash",
                "/src/.docker/run-docker-tests.sh",
            ]
            + list(pytest_args)
        )

        if result.returncode != 0:
            sys.exit(result.returncode)


# ── pre_commit ───────────────────────────────────────────────────────────────


def pre_commit(scope="all"):
    """
    Run pre-commit hooks.

    :param scope: 'all' to check all files (default), or omit for staged files only.

    Examples:
      python helper.py pre-commit        # staged files only
      python helper.py pre-commit all    # all files in the repo
    """
    cmd = ["pre-commit", "run"]
    if scope == "all":
        cmd.append("--all-files")

    label = "all files" if scope == "all" else "staged files"
    print(f"▶  Running pre-commit on {label} ...")

    result = subprocess.run(cmd, cwd=REPO_ROOT)
    if result.returncode not in (0, 1):  # 1 = hooks fixed/failed (expected)
        sys.exit(result.returncode)


# ── package ──────────────────────────────────────────────────────────────────

# Files required by QGIS / plugins.qgis.org in the package
REQUIRED_FILES = ["metadata.txt", "__init__.py"]

# Required keys in the [general] section of metadata.txt
REQUIRED_METADATA_KEYS = [
    "name",
    "qgisMinimumVersion",
    "description",
    "about",
    "version",
    "author",
    "email",
    "repository",
]

# Any of these license file variants is accepted
LICENSE_CANDIDATES = ["LICENSE", "LICENSE.txt", "LICENSE.md", "LICENSE.rst"]


def read_metadata():
    """Read metadata.txt and return a ConfigParser (exits if the file is missing)."""
    metadata_path = os.path.join(REPO_ROOT, "metadata.txt")
    if not os.path.isfile(metadata_path):
        print("Error: metadata.txt not found in the repository root.")
        sys.exit(1)

    cfg = ConfigParser(interpolation=None)  # avoid issues with '%' in the text
    cfg.optionxform = str  # preserve key case (e.g. qgisMinimumVersion)
    cfg.read(metadata_path, encoding="utf-8")
    return cfg


def validate_package_files(cfg):
    """
    Check that the files and metadata fields required by QGIS exist.
    Returns the list of problems found (empty list = everything is fine).
    """
    errors = []

    # 1) Required files
    for fname in REQUIRED_FILES:
        if not os.path.isfile(os.path.join(REPO_ROOT, fname)):
            errors.append(f"Missing required file: {fname}")

    # 2) License file (any variant)
    if not any(
        os.path.isfile(os.path.join(REPO_ROOT, name)) for name in LICENSE_CANDIDATES
    ):
        errors.append(
            "Missing license file (expected one of: "
            + ", ".join(LICENSE_CANDIDATES)
            + ")"
        )

    # 3) metadata.txt section and keys
    if not cfg.has_section("general"):
        errors.append("metadata.txt is missing the [general] section")
        return errors

    for key in REQUIRED_METADATA_KEYS:
        if not cfg.get("general", key, fallback="").strip():
            errors.append(f"metadata.txt: required field missing or empty: {key}")

    # 4) Icon referenced in metadata.txt must exist
    icon = cfg.get("general", "icon", fallback="").strip()
    if icon and not os.path.isfile(os.path.join(REPO_ROOT, icon)):
        errors.append(f"Icon referenced in metadata.txt does not exist: {icon}")

    return errors


def package():
    """
    Build a distributable .zip ready to install in QGIS.

    The version is read from metadata.txt and used in the file name
    (e.g., build/plugin_name-1.2.0.zip). Before packaging, the existence of the
    files required by QGIS (LICENSE, __init__.py, metadata.txt, ...) is checked.

    Plugin files at the repo root are zipped under plugin_name/. The archive is
    written to the build/ folder, which is excluded from the package.

    Example:
      python helper.py package
    """
    cfg = read_metadata()

    errors = validate_package_files(cfg)
    if errors:
        print("Could not build the package:")
        for err in errors:
            print(f"  ✗ {err}")
        sys.exit(1)

    version = re.sub(r"^v", "", cfg.get("general", "version").strip())
    print(f"Version (metadata.txt): {version}")

    translate()

    os.makedirs(BUILD_DIR, exist_ok=True)
    archive = os.path.join(BUILD_DIR, f"{PLUGIN_NAME}-{version}.zip")
    print(f"Creating {os.path.relpath(archive, REPO_ROOT)} ...")

    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
        for root, dirs, files in os.walk(REPO_ROOT):
            # Prune excluded directories in-place (this also skips build/)
            dirs[:] = [d for d in dirs if not _is_excluded(d)]

            for fname in files:
                if _is_excluded(fname):
                    continue
                abs_path = os.path.join(root, fname)
                rel_to_repo = os.path.relpath(abs_path, REPO_ROOT)
                zf.write(abs_path, os.path.join(PLUGIN_NAME, rel_to_repo))

    print(f"Build complete: {os.path.relpath(archive, REPO_ROOT)}")


# ── install ──────────────────────────────────────────────────────────────────


def install(qgis_version="3", target=None):
    """
    Install the plugin into your local QGIS profile via symlink (copy on Windows).

    The repo root is linked/copied as plugin_name/ inside the QGIS plugins folder.

    :param qgis_version: '3' or '4' (default: '3').
    :param target: 'flatpak' to force the Flatpak profile path, 'native' to
                   force the standard (non-Flatpak) path. Omit to auto-detect
                   — auto-detection only picks Flatpak if the QGIS Flatpak app
                   is actually installed.

    Examples:
      python helper.py install
      python helper.py install 4
      python helper.py install 3 flatpak
      python helper.py install 3 native
    """
    qgis_folder = f"QGIS{qgis_version}"

    if os.name == "nt":
        base = f"~/AppData/Roaming/QGIS/{qgis_folder}/profiles/default/python/plugins"
    elif sys.platform == "darwin":
        base = (
            f"~/Library/Application Support/QGIS/{qgis_folder}"
            "/profiles/default/python/plugins"
        )
    else:
        flatpak_base = f"~/.var/app/org.qgis.qgis/data/QGIS/{qgis_folder}/profiles/default/python/plugins"
        native_base = (
            f"~/.local/share/QGIS/{qgis_folder}/profiles/default/python/plugins"
        )

        if target == "flatpak":
            base = flatpak_base
        elif target == "native":
            base = native_base
        elif target is not None:
            print(f"Error: unknown target '{target}' (use 'flatpak' or 'native').")
            sys.exit(2)
        else:
            flatpak_app_installed = (
                shutil.which("flatpak") is not None
                and subprocess.run(
                    ["flatpak", "info", "org.qgis.qgis"],
                    stdout=subprocess.DEVNULL,
                    stderr=subprocess.DEVNULL,
                ).returncode
                == 0
            )
            base = flatpak_base if flatpak_app_installed else native_base

    plugins_dir = os.path.expanduser(base)
    os.makedirs(plugins_dir, exist_ok=True)
    dst = os.path.join(plugins_dir, PLUGIN_NAME)

    print(f"Installing to {dst} ...")

    if os.path.exists(dst) or os.path.islink(dst):
        try:
            os.remove(dst)
        except IsADirectoryError:
            shutil.rmtree(dst)

    if hasattr(os, "symlink"):
        os.symlink(REPO_ROOT, dst, target_is_directory=True)
        print("Symlink created — source changes are reflected immediately.")
    else:
        shutil.copytree(REPO_ROOT, dst)
        print("Directory copied.")


# ── publish ──────────────────────────────────────────────────────────────────


def publish(archive):
    """
    Upload the plugin zip to plugins.qgis.org via XML-RPC.

    Requires QGIS_CREDENTIALS=user:password in the environment.

    Example:
      QGIS_CREDENTIALS=myuser:mypass python helper.py publish build/plugin_name-1.2.0.zip
    """
    try:
        creds = os.environ["QGIS_CREDENTIALS"]
    except KeyError:
        print("Error: QGIS_CREDENTIALS not set (expected 'user:password').")
        sys.exit(2)

    url = f"https://{creds}@plugins.qgis.org/plugins/RPC2/"
    conn = xmlrpc.client.ServerProxy(url)
    print(f"Uploading {archive} to https://plugins.qgis.org ...")
    with open(archive, "rb") as fd:
        conn.plugin.upload(xmlrpc.client.Binary(fd.read()))
    print("Upload complete.")


