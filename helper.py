def usage():
    print(
        "Usage:\n"
        f"  {sys.argv[0]} install [3|4] [flatpak|native]        Install in local QGIS (default: 3, auto-detect)\n"
        f"  {sys.argv[0]} translate [LOCALE]                    Compile .ts → .qm files\n"
        f"  {sys.argv[0]} pytest [QGIS_VERSION] [PYTEST_ARGS]   Run tests in Docker (default: latest)\n"
        f"  {sys.argv[0]} pre-commit [all]                      Run pre-commit hooks (default: all files)\n"
        f"  {sys.argv[0]} package                               Build build/{PLUGIN_NAME}-<version>.zip (version from metadata.txt)\n"
        f"  {sys.argv[0]} publish ARCHIVE                       Upload zip to plugins.qgis.org\n",
        file=sys.stderr,
    )
    sys.exit(2)


args = sys.argv[1:]

if not args:
    usage()
elif args[0] == "install":
    install(*args[1:3])
elif args[0] == "translate":
    translate(*args[1:2])
elif args[0] == "pytest":
    run_tests(*args[1:])
elif args[0] == "pre-commit":
    pre_commit(*args[1:2])
elif args[0] == "package":
    package()
elif args[0] == "publish" and len(args) == 2:
    publish(args[1])
else:
    usage()
